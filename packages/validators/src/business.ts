import { z } from 'zod'
import {
  clearableText,
  optionalUrl,
  paginationSchema,
  slugSchema,
  whatsappNumberSchema,
} from './common'
import {
  PAIRED_COORDINATES_MESSAGE,
  clearableRtRw,
  latitudeSchema,
  longitudeSchema,
  pairedCoordinates,
  rtRwSchema,
} from './location'
import { openingHoursSchema } from './opening-hours'

const clearableUrl = z
  .union([z.url(), z.literal(''), z.null()])
  .optional()
  .transform((v) => (v === '' ? null : v))

const clearableWhatsApp = z
  .union([whatsappNumberSchema, z.literal(''), z.null()])
  .optional()
  .transform((v) => (v === '' ? null : v))

const nibSchema = z.string().regex(/^\d{13}$/, 'NIB terdiri dari 13 digit')

/**
 * Create a business. The slug is generated by the API from the name (and locked afterwards).
 * `consentGiven` = the owner signed the paper consent form (UU PDP); recorded as `paper_form`.
 */
export const businessCreateSchema = z
  .object({
    villageId: z.uuid(),
    name: z.string().trim().min(3).max(120),
    ownerName: z.string().trim().max(120).optional(),
    description: z.string().trim().max(2000).optional(),
    whatsappNumber: whatsappNumberSchema.optional(),
    /** Street or landmark. Internal: never shown on public pages. */
    address: z.string().trim().max(300).optional(),
    rt: rtRwSchema.optional().or(z.literal('').transform(() => undefined)),
    rw: rtRwSchema.optional().or(z.literal('').transform(() => undefined)),
    /** Map pin (internal). Both or neither. */
    lat: latitudeSchema.optional(),
    lng: longitudeSchema.optional(),
    shopeeUrl: optionalUrl,
    tokopediaUrl: optionalUrl,
    tiktokShopUrl: optionalUrl,
    instagramUrl: optionalUrl,
    nib: nibSchema.optional().or(z.literal('').transform(() => undefined)),
    openingHours: openingHoursSchema.optional(),
    consentGiven: z.boolean().default(false),
  })
  .refine(pairedCoordinates, { message: PAIRED_COORDINATES_MESSAGE, path: ['lat'] })

/**
 * Partial update. Missing field = unchanged, '' or null = cleared.
 * No defaults here on purpose: a default would silently overwrite stored values on every edit
 * (the earlier `.partial()` of the create schema revoked consent on each PATCH).
 * `slug` is accepted but only village admins may change it (`business.change_slug`).
 * `consentGiven: false` withdraws consent and unpublishes the business.
 */
export const businessUpdateSchema = z
  .object({
    name: z.string().trim().min(3).max(120).optional(),
    slug: slugSchema.optional(),
    ownerName: clearableText(120),
    description: clearableText(2000),
    whatsappNumber: clearableWhatsApp,
    address: clearableText(300),
    rt: clearableRtRw,
    rw: clearableRtRw,
    /** null clears the pin; send both together. */
    lat: latitudeSchema.nullish(),
    lng: longitudeSchema.nullish(),
    shopeeUrl: clearableUrl,
    tokopediaUrl: clearableUrl,
    tiktokShopUrl: clearableUrl,
    instagramUrl: clearableUrl,
    nib: z
      .union([nibSchema, z.literal(''), z.null()])
      .optional()
      .transform((v) => (v === '' ? null : v)),
    openingHours: openingHoursSchema.nullish(),
    closedUntil: z.iso.datetime({ offset: true }).nullish(),
    closedNote: clearableText(200),
    consentGiven: z.boolean().optional(),
  })
  .refine(pairedCoordinates, { message: PAIRED_COORDINATES_MESSAGE, path: ['lat'] })

export const businessVerifySchema = z
  .object({
    decision: z.enum(['verified', 'rejected']),
    note: z.string().trim().max(500).optional(),
  })
  .refine((v) => v.decision === 'verified' || (v.note && v.note.length >= 5), {
    message: 'Tulis alasan penolakan (min. 5 karakter)',
    path: ['note'],
  })

export const businessTakedownSchema = z.object({
  reason: z.string().trim().min(5).max(500),
})

/** Dashboard list filters (`GET /v1/manage/businesses`). */
export const businessManageListQuerySchema = paginationSchema.extend({
  villageId: z.uuid().optional(),
  verificationStatus: z.enum(['pending', 'verified', 'rejected']).optional(),
  status: z.enum(['draft', 'published', 'archived']).optional(),
  q: z.string().trim().max(100).optional(),
})

export type BusinessCreateInput = z.infer<typeof businessCreateSchema>
export type BusinessUpdateInput = z.infer<typeof businessUpdateSchema>
export type BusinessVerifyInput = z.infer<typeof businessVerifySchema>
export type BusinessTakedownInput = z.infer<typeof businessTakedownSchema>
