import { z } from 'zod'
import { clearableText, paginationSchema } from './common'

export const MIN_PRODUCT_PRICE = 100
const MAX_PRICE = 1_000_000_000

/**
 * Selling price in whole rupiah. 0 = free ("Gratis"); otherwise at least Rp100, so a typo such as
 * "5" is rejected. JSON numbers only (no coercion: `Number('')` would silently be 0 = free).
 */
export const productPriceSchema = z
  .number()
  .int()
  .min(0)
  .max(MAX_PRICE)
  .refine((v) => v === 0 || v >= MIN_PRODUCT_PRICE, 'Harga minimal Rp100, atau 0 untuk gratis')

/** Normal price shown struck through; must be higher than the selling price. */
export const compareAtPriceSchema = z.number().int().min(MIN_PRODUCT_PRICE).max(MAX_PRICE)

export const COMPARE_AT_PRICE_MESSAGE = 'Harga coret harus lebih tinggi dari harga jual'

const productNameSchema = z.string().trim().min(3).max(120)

/** English translation; falls back to the Indonesian text when missing. */
const productEnSchema = z.object({
  name: productNameSchema,
  description: clearableText(3000),
})

/**
 * Create a product inside a business (`POST /v1/manage/businesses/{id}/products`).
 * The slug is generated by the API from the name; the village comes from the business.
 */
export const productCreateSchema = z
  .object({
    categoryId: z.uuid(),
    name: productNameSchema,
    description: z.string().trim().max(3000).optional(),
    price: productPriceSchema,
    compareAtPrice: compareAtPriceSchema.optional(),
    /** e.g. "pcs", "pack 250 gr", "kg". Variants are separate products (MVP). */
    unit: z.string().trim().max(40).optional(),
    isAvailable: z.boolean().default(true),
    en: productEnSchema.optional(),
  })
  .refine((v) => v.compareAtPrice === undefined || v.compareAtPrice > v.price, {
    message: COMPARE_AT_PRICE_MESSAGE,
    path: ['compareAtPrice'],
  })

/**
 * Partial update. Missing field = unchanged, '' or null = cleared. No defaults on purpose (a default
 * `isAvailable: true` would mark a sold-out product available again on every edit).
 * `compareAtPrice > price` is checked by the API against the stored row.
 * `en: null` removes the English translation.
 */
export const productUpdateSchema = z.object({
  categoryId: z.uuid().optional(),
  name: productNameSchema.optional(),
  description: clearableText(3000),
  price: productPriceSchema.optional(),
  compareAtPrice: compareAtPriceSchema.nullish(),
  unit: clearableText(40),
  isAvailable: z.boolean().optional(),
  en: productEnSchema.nullish(),
})

/** Dashboard list filters (`GET /v1/manage/businesses/{id}/products`). */
export const productManageListQuerySchema = paginationSchema.extend({
  status: z.enum(['draft', 'published', 'archived']).optional(),
  q: z.string().trim().max(100).optional(),
})

export const productSearchSchema = paginationSchema.extend({
  q: z.string().trim().max(100).optional(),
  category: z.string().optional(),
  /** Any Kemendagri region code prefix: "32" (province), "32.04" (regency), ... */
  region: z.string().optional(),
  village: z.string().optional(),
  sort: z.enum(['newest', 'price_asc', 'price_desc']).default('newest'),
})

/** Percent off for a "-20%" badge; null when there is no real discount or the product is free. */
export function discountPercent(price: number, compareAtPrice: number | null): number | null {
  if (!compareAtPrice || price <= 0 || compareAtPrice <= price) return null
  const pct = Math.floor(((compareAtPrice - price) / compareAtPrice) * 100)
  return pct >= 1 ? pct : null
}

export type ProductCreateInput = z.infer<typeof productCreateSchema>
export type ProductUpdateInput = z.infer<typeof productUpdateSchema>
export type ProductManageListQuery = z.infer<typeof productManageListQuerySchema>
export type ProductSearchInput = z.infer<typeof productSearchSchema>
